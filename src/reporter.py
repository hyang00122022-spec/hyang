"""P1: Final report generation module.

Produces the final report containing:
- Cash in (total receipts)
- Cash out (total invoices paid)
- Net cash flow
- Category breakdown (S5)
- Top 3 recommended actions
"""

from __future__ import annotations

from collections import defaultdict

from .config import CATEGORY_CODES
from .models import (
    CategorySummary,
    ChaseEmail,
    DocumentInfo,
    FinalReport,
    PipelineResult,
    Task,
)


class Reporter:
    """Generates the final report from pipeline results."""

    def generate(
        self,
        goal: str,
        documents: list[DocumentInfo] | None = None,
        tasks: list[Task] | None = None,
        chase_emails: list[ChaseEmail] | None = None,
        exceptions_count: int = 0,
    ) -> FinalReport:
        """Generate a final report from the pipeline results.

        Args:
            goal: The original goal string.
            documents: Documents processed by Logistics.
            tasks: Tasks generated by the Secretary.
            chase_emails: Chase emails drafted.
            exceptions_count: Total exceptions raised by Financial.

        Returns:
            A FinalReport object.
        """
        documents = documents or []
        tasks = tasks or []
        chase_emails = chase_emails or []

        cash_in, cash_out = self._calculate_cash_flow(documents)
        categories = self._categorize(documents)
        top_3 = self._generate_top_3_actions(tasks, chase_emails, documents)

        # Extract period from goal (e.g., "Close out September" -> "September")
        period = self._extract_period(goal)

        approved_count = sum(
            1 for e in chase_emails
            if e.status.value in ("approved", "sent")
        )

        return FinalReport(
            goal=goal,
            period=period,
            cash_in=cash_in,
            cash_out=cash_out,
            categories=categories,
            top_3_actions=top_3,
            total_exceptions=exceptions_count,
            tasks_generated=len(tasks),
            chase_emails_drafted=len(chase_emails),
            chase_emails_approved=approved_count,
        )

    # ------------------------------------------------------------------
    # Cash flow calculation
    # ------------------------------------------------------------------

    def _calculate_cash_flow(
        self, documents: list[DocumentInfo]
    ) -> tuple[float, float]:
        """Calculate cash in (receipts) and cash out (invoices).

        Args:
            documents: All processed documents.

        Returns:
            Tuple of (cash_in, cash_out).
        """
        cash_in = 0.0
        cash_out = 0.0

        for doc in documents:
            if doc.doc_type.lower() == "receipt":
                cash_in += doc.grand_total
            else:
                # Invoices and POs are outgoing
                cash_out += doc.grand_total

        return round(cash_in, 2), round(cash_out, 2)

    # ------------------------------------------------------------------
    # Categorization (S5)
    # ------------------------------------------------------------------

    def _categorize(
        self, documents: list[DocumentInfo]
    ) -> list[CategorySummary]:
        """Break down spending by category (S5).

        Args:
            documents: All processed documents.

        Returns:
            List of CategorySummary objects, sorted by total descending.
        """
        category_totals: dict[str, dict] = defaultdict(
            lambda: {"total": 0.0, "count": 0}
        )

        for doc in documents:
            # Try to find category from line items, fallback to "UNCATEGORIZED"
            category = "UNCATEGORIZED"
            for item in doc.line_items:
                cat = item.get("category", item.get("cat", ""))
                if cat and cat in CATEGORY_CODES:
                    category = cat
                    break

            category_totals[category]["total"] += doc.grand_total
            category_totals[category]["count"] += 1

        summaries = [
            CategorySummary(
                category=cat,
                total=round(data["total"], 2),
                count=data["count"],
            )
            for cat, data in category_totals.items()
        ]

        # Sort by total descending
        summaries.sort(key=lambda x: x.total, reverse=True)
        return summaries

    # ------------------------------------------------------------------
    # Top 3 actions
    # ------------------------------------------------------------------

    def _generate_top_3_actions(
        self,
        tasks: list[Task],
        chase_emails: list[ChaseEmail],
        documents: list[DocumentInfo],
    ) -> list[str]:
        """Generate the top 3 recommended actions from the pipeline results.

        Priority order:
        1. P1 critical tasks (duplicates, large escalations)
        2. Overdue chase emails needing approval
        3. High-value escalation tasks
        4. Fallback: general recommendations

        Args:
            tasks: All generated tasks.
            chase_emails: All drafted chase emails.
            documents: All processed documents.

        Returns:
            List of up to 3 action strings.
        """
        actions: list[str] = []

        # 1. Critical tasks first (P1 = duplicates, large escalations)
        critical_tasks = [
            t for t in tasks
            if t.priority.value <= 1
        ]
        for task in critical_tasks[:1]:
            actions.append(
                f"URGENT: {task.title} — {task.action_required}"
            )

        # 2. Chase emails needing approval
        pending_emails = [
            e for e in chase_emails
            if e.status.value == "draft"
        ]
        if pending_emails:
            actions.append(
                f"Review and approve {len(pending_emails)} chase email(s) "
                f"for overdue invoices."
            )

        # 3. High-priority tasks
        high_tasks = [
            t for t in tasks
            if t.priority.value == 2
        ]
        if high_tasks:
            actions.append(
                f"Address {len(high_tasks)} high-priority task(s): "
                f"{', '.join(t.title[:40] for t in high_tasks[:3])}"
            )

        # Fallbacks if we don't have enough actions
        if not actions:
            actions.append(
                f"Process {len(documents)} document(s) through the pipeline."
            )

        if len(actions) < 3:
            if documents:
                actions.append(
                    f"Verify ledger entries for {len(documents)} processed document(s)."
                )

        if len(actions) < 3:
            actions.append(
                "Schedule a monthly reconciliation review."
            )

        return actions[:3]

    # ------------------------------------------------------------------
    # Period extraction
    # ------------------------------------------------------------------

    def _extract_period(self, goal: str) -> str:
        """Try to extract a time period from the goal string.

        Examples:
            "Close out September" -> "September"
            "Reconcile October 2026" -> "October 2026"
            "Process invoices" -> "Current period"

        Args:
            goal: The user's goal string.

        Returns:
            Extracted period or "Current period".
        """
        months = [
            "January", "February", "March", "April", "May", "June",
            "July", "August", "September", "October", "November", "December",
            "Jan", "Feb", "Mar", "Apr", "May", "Jun",
            "Jul", "Aug", "Sep", "Oct", "Nov", "Dec",
        ]

        goal_words = goal.split()
        for i, word in enumerate(goal_words):
            # Check if any month name matches (case-insensitive)
            for month in months:
                if word.lower() == month.lower():
                    # Check for year following the month
                    if i + 1 < len(goal_words):
                        next_word = goal_words[i + 1]
                        if next_word.isdigit() and len(next_word) == 4:
                            return f"{month} {next_word}"
                    return month

        return "Current period"

    # ------------------------------------------------------------------
    # Report formatting
    # ------------------------------------------------------------------

    def format_report(self, report: FinalReport) -> str:
        """Format the final report as human-readable text.

        Args:
            report: The FinalReport object.

        Returns:
            Multi-line formatted string.
        """
        lines = [
            "=" * 60,
            f"  FINAL REPORT: {report.goal}",
            f"  Period: {report.period}",
            f"  Generated: {report.generated_at}",
            "=" * 60,
            "",
            "  CASH FLOW SUMMARY",
            f"    Cash In:   RM {report.cash_in:>12,.2f}",
            f"    Cash Out:  RM {report.cash_out:>12,.2f}",
            f"    Net Cash:  RM {report.net_cash:>12,.2f}",
            "",
            "  CATEGORY BREAKDOWN",
        ]

        if report.categories:
            for cat in report.categories:
                cat_name = CATEGORY_CODES.get(cat.category, cat.category)
                lines.append(
                    f"    {cat.category:6s} {cat_name:30s} "
                    f"RM {cat.total:>10,.2f}  ({cat.count} docs)"
                )
        else:
            lines.append("    (no categorized documents)")

        lines.extend([
            "",
            "  PIPELINE STATISTICS",
            f"    Exceptions raised:   {report.total_exceptions}",
            f"    Tasks generated:     {report.tasks_generated}",
            f"    Chase emails drafted: {report.chase_emails_drafted}",
            f"    Chase emails approved: {report.chase_emails_approved}",
            "",
            "  TOP 3 RECOMMENDED ACTIONS",
        ])

        for i, action in enumerate(report.top_3_actions, 1):
            lines.append(f"    {i}. {action}")

        lines.extend(["", "=" * 60])
        return "\n".join(lines)
